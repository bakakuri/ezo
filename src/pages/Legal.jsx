function LegalPage({ title, children }) {
  const { session } = useAuth()
  useEffect(() => {
    const before = document.title
    document.title = `${title} — ეზო`
    return () => { document.title = before }
  }, [title])
  return (
    <div className={`legal-wrap${session ? '' : ' standalone'}`}>
      <TopBar title={title} backTo={session ? '/settings' : '/'} />
      <article className="legal">
        {children}
        <p className="legal-date">ბოლო განახლება: {UPDATED}</p>
        {!session && <p className="legal-back"><Link to="/" className="btn btn-accent">ეზოში შესვლა</Link></p>}
      </article>
    </div>
  )
}
